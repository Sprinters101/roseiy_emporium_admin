// In-memory / storage backed store
let ordersStore: OrderRecord[] = [...initialOrdersList];
const listeners = new Set<() => void>();

export const getOrders = (): OrderRecord[] => ordersStore;

export const getOrderByIdOrNumber = (
    idOrNumber: string,
): OrderRecord | undefined => {
    return (
        ordersStore.find(
            (o) =>
                o.id === idOrNumber ||
                o.orderNumber === idOrNumber ||
                `Order ${o.orderNumber}` === idOrNumber,
        ) || ordersStore[0]
    );
};

export const updateOrderStatus = (
    orderId: string,
    newProgress: OrderProgressStatus,
): OrderRecord | undefined => {
    const now = "29 July 2026 at 10:42PM";
    ordersStore = ordersStore.map((o) => {
        if (o.id === orderId || o.orderNumber === orderId) {
            let category: OrderCategory = "ongoing";
            const updated = { ...o, progress: newProgress };
            if (newProgress === "Order Confirmed") {
                updated.confirmedAt = now;
            } else if (newProgress === "InTransit") {
                updated.inTransitAt = now;
            } else if (newProgress === "Delivered") {
                updated.deliveredAt = "29 July 2026 at 11:12PM";
                category = "completed";
            } else if (newProgress === "Failed") {
                updated.failedAt = now;
                category = "failed";
            }
            updated.category = category;
            return updated;
        }
        return o;
    });
    listeners.forEach((l) => l());
    return getOrderByIdOrNumber(orderId);
};

export const subscribeOrders = (listener: () => void) => {
    listeners.add(listener);
    return () => {
        listeners.delete(listener);
    };
};
