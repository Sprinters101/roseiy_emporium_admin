export interface OrderProductItem {
    id: string;
    name: string;
    brand: string;
    price: number;
    quantity: string;
    subtotal: number;
    image: string;
}

export type OrderProgressStatus =
    | "Order Placed"
    | "Order Confirmed"
    | "InTransit"
    | "Delivered"
    | "Failed";

export type OrderCategory = "ongoing" | "completed" | "failed";

export interface OrderRecord {
    id: string;
    orderNumber: string;
    customerName: string;
    customerEmail: string;
    customerPhone: string;
    deliveryAddress: string;
    amount: number;
    subtotal: number;
    deliveryFee: number;
    progress: OrderProgressStatus;
    category: OrderCategory;
    date: string;
    placedAt: string;
    confirmedAt?: string;
    inTransitAt?: string;
    deliveredAt?: string;
    failedAt?: string;
    paymentStatus: "Completed" | "Pending" | "Failed";
    items: OrderProductItem[];
}

